-- BUSNIESS PROBLEM: HOW DO CREDIT LIMITS DIFFER BETWEEN CUSTOMERS WHO DEFAULTED AND THOSE WHO DID NOT?


-- COMPARE AVERAGE CREDIT LIMIT
SELECT
    default_payment_next_month AS DEFAULT_STATUS,
    COUNT(*) AS TOTAL_CUSTOMERS,
    AVG(CAST(LIMIT_BAL AS BIGINT)) AS AVG_CREDIT_LIMIT,
    MIN(LIMIT_BAL) AS MIN_CREDIT_LIMIT,
    MAX(LIMIT_BAL) AS MAX_CREDIT_LIMIT
FROM dbo.CreditCardData
GROUP BY default_payment_next_month
ORDER BY default_payment_next_month;


-- COMPARE DEFAULT RATES ACROSS CREDIT LIMIT RANGES

SELECT
    CASE
        WHEN LIMIT_BAL < 50000 THEN 'BELOW 50K'
        WHEN LIMIT_BAL < 100000 THEN '50K-99,999'
        WHEN LIMIT_BAL < 200000 THEN '100K-199,999'
        WHEN LIMIT_BAL < 500000 THEN '200K-499,999'
        ELSE '500K AND ABOVE'
    END AS CREDIT_LIMIT_RANGE,
    COUNT(*) AS TOTAL_CUSTOMERS,
    SUM(CASE
        WHEN default_payment_next_month = 1 THEN 1
        ELSE 0
    END) AS DEFAULTED_CUSTOMERS,
    CAST(
        100.0 * SUM(CASE
            WHEN default_payment_next_month = 1 THEN 1
            ELSE 0
        END) / COUNT(*) AS DECIMAL(5,2)
    ) AS DEFAULT_RATE_PERCENT
FROM dbo.CreditCardData
GROUP BY
    CASE
        WHEN LIMIT_BAL < 50000 THEN 'BELOW 50K'
        WHEN LIMIT_BAL < 100000 THEN '50K-99,999'
        WHEN LIMIT_BAL < 200000 THEN '100K-199,999'
        WHEN LIMIT_BAL < 500000 THEN '200K-499,999'
        ELSE '500K AND ABOVE'
    END
ORDER BY
    MIN(LIMIT_BAL);


-- COMPARE CREDIT LIMIT DISTRIBUTION BY DEFAULT STATUS
WITH CREDIT_GROUPS AS (
    SELECT
        CASE
            WHEN LIMIT_BAL < 50000 THEN 'BELOW 50K'
            WHEN LIMIT_BAL < 100000 THEN '50K-99,999'
            WHEN LIMIT_BAL < 200000 THEN '100K-199,999'
            WHEN LIMIT_BAL < 500000 THEN '200K-499,999'
            ELSE '500K AND ABOVE'
        END AS CREDIT_LIMIT_RANGE,
        default_payment_next_month AS DEFAULT_STATUS
    FROM dbo.CreditCardData
)
SELECT
    CREDIT_LIMIT_RANGE,
    DEFAULT_STATUS,
    COUNT(*) AS TOTAL_CUSTOMERS,
    CAST(
        100.0 * COUNT(*) /
        SUM(COUNT(*)) OVER (PARTITION BY DEFAULT_STATUS)
        AS DECIMAL(5,2)
    ) AS PERCENT_WITHIN_DEFAULT_STATUS
FROM CREDIT_GROUPS
GROUP BY CREDIT_LIMIT_RANGE, DEFAULT_STATUS
ORDER BY
    DEFAULT_STATUS,
    CASE CREDIT_LIMIT_RANGE
        WHEN 'BELOW 50K' THEN 1
        WHEN '50K-99,999' THEN 2
        WHEN '100K-199,999' THEN 3
        WHEN '200K-499,999' THEN 4
        ELSE 5
    END;

