-- BUSINESS PROBLEM: ARE HIGHER BILL AMOUNTS ASSOCIATED WITH HIGHER DEFAULT RATES?


-- COMPARE AVERAGE BILL AMOUNTS
SELECT
    default_payment_next_month AS DEFAULT_STATUS,
    COUNT(*) AS TOTAL_CUSTOMERS,
    AVG(CAST(BILL_AMT1 AS BIGINT)) AS AVG_BILL_AMT1,
    AVG(CAST(BILL_AMT2 AS BIGINT)) AS AVG_BILL_AMT2,
    AVG(CAST(BILL_AMT3 AS BIGINT)) AS AVG_BILL_AMT3,
    AVG(CAST(BILL_AMT4 AS BIGINT)) AS AVG_BILL_AMT4,
    AVG(CAST(BILL_AMT5 AS BIGINT)) AS AVG_BILL_AMT5,
    AVG(CAST(BILL_AMT6 AS BIGINT)) AS AVG_BILL_AMT6
FROM dbo.CreditCardData
GROUP BY default_payment_next_month
ORDER BY default_payment_next_month;


-- COMPARE AVERAGE BILL AMOUNT RANGES
SELECT
    CASE
        WHEN BILL_AMT1 < 0 THEN 'NEGATIVE BILL'
        WHEN BILL_AMT1 < 10000 THEN '0-9,999'
        WHEN BILL_AMT1 < 50000 THEN '10K-49,999'
        WHEN BILL_AMT1 < 100000 THEN '50K-99,999'
        WHEN BILL_AMT1 < 200000 THEN '100K-199,999'
        ELSE '200K AND ABOVE'
    END AS BILL_AMOUNT_RANGE,
    COUNT(*) AS TOTAL_CUSTOMERS,
    SUM(CASE
        WHEN default_payment_next_month = 1 THEN 1
        ELSE 0
    END) AS DEFAULTED_CUSTOMERS,
    CAST(
        100.0 * SUM(CASE
            WHEN default_payment_next_month = 1 THEN 1
            ELSE 0
        END) / COUNT(*) AS DECIMAL(5,2)
    ) AS DEFAULT_RATE_PERCENT
FROM dbo.CreditCardData
GROUP BY
    CASE
        WHEN BILL_AMT1 < 0 THEN 'NEGATIVE BILL'
        WHEN BILL_AMT1 < 10000 THEN '0-9,999'
        WHEN BILL_AMT1 < 50000 THEN '10K-49,999'
        WHEN BILL_AMT1 < 100000 THEN '50K-99,999'
        WHEN BILL_AMT1 < 200000 THEN '100K-199,999'
        ELSE '200K AND ABOVE'
    END
ORDER BY MIN(BILL_AMT1);


-- COMPARE BILL AMOUNTS WITH PAYMENT AMOUNTS

SELECT
    default_payment_next_month AS DEFAULT_STATUS,
    COUNT(*) AS TOTAL_CUSTOMERS,
    AVG(CAST(BILL_AMT1 AS BIGINT)) AS AVG_BILL_AMOUNT,
    AVG(CAST(PAY_AMT1 AS BIGINT)) AS AVG_PAYMENT_AMOUNT,
    AVG(CAST(BILL_AMT1 - PAY_AMT1 AS BIGINT)) AS AVG_BILL_MINUS_PAYMENT
FROM dbo.CreditCardData
GROUP BY default_payment_next_month
ORDER BY default_payment_next_month;



-- PAYMENT-TO-BILL RATIO
WITH PAYMENT_RATIO AS (
    SELECT
        CASE
            WHEN 1.0 * PAY_AMT1 / NULLIF(BILL_AMT1, 0) < 0.10
                THEN 'BELOW 10%'
            WHEN 1.0 * PAY_AMT1 / NULLIF(BILL_AMT1, 0) < 0.50
                THEN '10%-49.99%'
            WHEN 1.0 * PAY_AMT1 / NULLIF(BILL_AMT1, 0) < 1.00
                THEN '50%-99.99%'
            ELSE '100% AND ABOVE'
        END AS PAYMENT_TO_BILL_RATIO,
        default_payment_next_month AS DEFAULT_STATUS
    FROM dbo.CreditCardData
    WHERE BILL_AMT1 > 0
)
SELECT
    PAYMENT_TO_BILL_RATIO,
    COUNT(*) AS TOTAL_CUSTOMERS,
    SUM(CASE WHEN DEFAULT_STATUS = 1 THEN 1 ELSE 0 END)
        AS DEFAULTED_CUSTOMERS,
    CAST(
        100.0 * SUM(CASE WHEN DEFAULT_STATUS = 1 THEN 1 ELSE 0 END)
        / COUNT(*) AS DECIMAL(5,2)
    ) AS DEFAULT_RATE_PERCENT
FROM PAYMENT_RATIO
GROUP BY PAYMENT_TO_BILL_RATIO
ORDER BY
    CASE PAYMENT_TO_BILL_RATIO
        WHEN 'BELOW 10%' THEN 1
        WHEN '10%-49.99%' THEN 2
        WHEN '50%-99.99%' THEN 3
        ELSE 4
    END;


--Compare payment ratios across all six months

WITH MONTHLY_RATIOS AS (
    SELECT
        V.MONTH_NAME,
        V.BILL_AMOUNT,
        V.PAYMENT_AMOUNT,
        D.default_payment_next_month AS DEFAULT_STATUS,
        CASE
            WHEN 1.0 * V.PAYMENT_AMOUNT / NULLIF(V.BILL_AMOUNT, 0) < 0.10
                THEN 'BELOW 10%'
            WHEN 1.0 * V.PAYMENT_AMOUNT / NULLIF(V.BILL_AMOUNT, 0) < 0.50
                THEN '10%-49.99%'
            WHEN 1.0 * V.PAYMENT_AMOUNT / NULLIF(V.BILL_AMOUNT, 0) < 1.00
                THEN '50%-99.99%'
            ELSE '100% AND ABOVE'
        END AS PAYMENT_TO_BILL_RATIO
    FROM dbo.CreditCardData AS D
    CROSS APPLY (VALUES
        ('MONTH 1', D.BILL_AMT1, D.PAY_AMT1),
        ('MONTH 2', D.BILL_AMT2, D.PAY_AMT2),
        ('MONTH 3', D.BILL_AMT3, D.PAY_AMT3),
        ('MONTH 4', D.BILL_AMT4, D.PAY_AMT4),
        ('MONTH 5', D.BILL_AMT5, D.PAY_AMT5),
        ('MONTH 6', D.BILL_AMT6, D.PAY_AMT6)
    ) AS V(MONTH_NAME, BILL_AMOUNT, PAYMENT_AMOUNT)
    WHERE V.BILL_AMOUNT > 0
)
SELECT
    MONTH_NAME,
    PAYMENT_TO_BILL_RATIO,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE WHEN DEFAULT_STATUS = 1 THEN 1 ELSE 0 END)
        AS DEFAULTED_RECORDS,
    CAST(
        100.0 * SUM(CASE WHEN DEFAULT_STATUS = 1 THEN 1 ELSE 0 END)
        / COUNT(*) AS DECIMAL(5,2)
    ) AS DEFAULT_RATE_PERCENT
FROM MONTHLY_RATIOS
GROUP BY MONTH_NAME, PAYMENT_TO_BILL_RATIO
ORDER BY
    CASE MONTH_NAME
        WHEN 'MONTH 1' THEN 1
        WHEN 'MONTH 2' THEN 2
        WHEN 'MONTH 3' THEN 3
        WHEN 'MONTH 4' THEN 4
        WHEN 'MONTH 5' THEN 5
        ELSE 6
    END,
    CASE PAYMENT_TO_BILL_RATIO
        WHEN 'BELOW 10%' THEN 1
        WHEN '10%-49.99%' THEN 2
        WHEN '50%-99.99%' THEN 3
        ELSE 4
    END;

